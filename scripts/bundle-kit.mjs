// Bundle kit/skills and kit/templates into the Worker as src/kit.generated.ts,
// so skills and the event template ship with every deploy (no git clone per
// call, nothing to push to a separate repo). Runs from wrangler's build
// command and from `npm run check`.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const kit = join(root, "kit");
const DIRS = ["skills", "templates"];
const SKIP = new Set([".DS_Store"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    if (SKIP.has(name)) return [];
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = {};
for (const d of DIRS) {
  for (const full of walk(join(kit, d)).sort()) {
    files[relative(kit, full).split(sep).join("/")] = readFileSync(full, "utf8");
  }
}

writeFileSync(
  join(root, "src", "kit.generated.ts"),
  `// Generated by scripts/bundle-kit.mjs from kit/. Don't edit; edit kit/ and rebuild.\n` +
    `export const KIT: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`bundle-kit: ${Object.keys(files).length} files from kit/${DIRS.join(", kit/")}`);
